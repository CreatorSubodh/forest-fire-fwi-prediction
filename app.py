import streamlit as st
import numpy as np
import pickle


# PAGE CONFIGURATION

st.set_page_config(
    page_title="Forest Fire FWI Predictor",
    page_icon="🔥",
    layout="centered"
)

# LOAD MODEL AND SCALER

model = pickle.load(
    open("models/linear_regression.pkl", "rb")
)

scaler = pickle.load(
    open("models/scaler.pkl", "rb")
)


# HEADER

st.title("Algerian Forest Fire FWI Predictor")

st.write(
    "Estimate the Fire Weather Index (FWI) using "
    "weather conditions and fire-weather indicators."
)

st.caption(
    "Machine Learning model trained on the Algerian Forest Fires dataset."
)


# WEATHER CONDITIONS

with st.container(border=True):

    st.subheader("🌤️ Weather Conditions")

    col1, col2 = st.columns(2)

    with col1:

        temperature = st.number_input(
            "Temperature (°C)",
            value=30.0,
            step=0.1
        )

        ws = st.number_input(
            "Wind Speed (km/h)",
            value=15.0,
            step=0.1
        )

    with col2:

        rh = st.number_input(
            "Relative Humidity (%)",
            value=50.0,
            step=0.1
        )

        rain = st.number_input(
            "Rain (mm)",
            value=0.0,
            step=0.1
        )

# FIRE WEATHER INDICATORS

with st.container(border=True):

    st.subheader("🔥 Fire Weather Indicators")

    col1, col2 = st.columns(2)

    with col1:

        ffmc = st.number_input(
            "Fine Fuel Moisture Code (FFMC)",
            value=80.0,
            step=0.1,
            help="Fine Fuel Moisture Code"
        )

        isi = st.number_input(
            "Initial Spread Index (ISI)",
            value=5.0,
            step=0.1,
            help="Initial Spread Index"
        )

    with col2:

        dmc = st.number_input(
            "Duff Moisture Code (DMC)",
            value=20.0,
            step=0.1,
            help="Duff Moisture Code"
        )

        region_name = st.selectbox(
            "Region",
            ["Bejaia", "Sidi-Bel Abbes"]
        )

region = 0 if region_name == "Bejaia" else 1

# PREDICTION
st.write("")

predict_button = st.button(
    "🔥 Predict FWI",
    use_container_width=True,
    type="primary"
)


if predict_button:
    input_data = np.array([[
        temperature,
        rh,
        ws,
        rain,
        ffmc,
        dmc,
        isi,
        region
    ]])

    input_scaled = scaler.transform(input_data)
    prediction = model.predict(input_scaled)

    fwi = prediction[0]


# RESULT
    st.divider()

    with st.container(border=True):

        st.subheader("📊 Prediction Result")

        st.metric(
            label="Predicted Fire Weather Index",
            value=f"{fwi:.2f}"
        )

        if fwi < 5:

            st.success(
                "Low fire-weather conditions."
            )

        elif fwi < 10:

            st.warning(
                "Moderate fire-weather conditions."
            )

        else:

            st.error(
                "High fire-weather conditions."
            )


# INFORMATION
    with st.expander("What is FWI?"):

        st.write(
            "The Fire Weather Index (FWI) is a numerical indicator "
            "used to represent fire-weather conditions based on "
            "weather and fire-weather variables."
        )

        st.write(
            "The prediction shown above is generated by the "
            "trained Linear Regression model used in this project."
        )


# FOOTER
st.divider()

st.caption(
    "Algerian Forest Fire FWI Prediction • Machine Learning Project"
)